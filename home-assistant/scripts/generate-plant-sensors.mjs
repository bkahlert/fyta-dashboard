#!/usr/bin/env node
// Purpose: Generate HA template sensor YAML for FYTA plant moisture bridges.
// Usage:   HA_TOKEN=<token> node scripts/generate-plant-sensors.mjs [output-path]

import { writeFileSync, mkdirSync } from "fs";
import { dirname } from "path";

const TOKEN = process.env.HA_TOKEN;
if (!TOKEN) {
  console.error("HA_TOKEN not set");
  process.exit(1);
}

const outputPath = process.argv[2] || "config/fyta_plant_sensors.yaml";

function toTitleCase(str) {
  return str.replace(/_/g, " ").replace(/\b\w/g, (c) => c.toUpperCase());
}

function generateYaml(prefixes) {
  const sensors = prefixes
    .map((p) =>
      [
        `      - name: "${toTitleCase(p)} Plant"`,
        `        unique_id: ${p}_plant`,
        `        state: "{{ states('sensor.${p}_moisture') | float(0) }}"`,
        `        unit_of_measurement: "%"`,
        `        device_class: moisture`,
        `        state_class: measurement`,
        `        attributes:`,
        `          moisture_state: "{{ states('sensor.${p}_moisture_state') }}"`,
        `          device_name: "{{ device_attr(device_id('sensor.${p}_moisture_state'), 'name') }}"`,
        `          scientific_name: "{{ states('sensor.${p}_scientific_name') }}"`,
        `          picture_url: "{{ state_attr('image.${p}', 'entity_picture') }}"`,
        `          temperature_state: "{{ states('sensor.${p}_temperature_state') }}"`,
        `          light_state: "{{ states('sensor.${p}_light_state') }}"`,
        `          nutrients_state: "{{ states('sensor.${p}_nutrients_state') }}"`,
        `          battery: "{{ states('sensor.${p}_battery') | int(0) }}"`,
        `          next_fertilization: "{{ states('sensor.${p}_next_fertilization') }}"`,
        `          benutzerbild_url: "{%- set _fn = state_attr('sensor.${p}_moisture', 'friendly_name') -%}{%- set _slug = _fn.split(' ')[:-1] | join('_') | lower | replace('ü','u') | replace('ö','o') | replace('ä','a') | replace('ß','ss') -%}{{ state_attr('image.' + _slug + '_benutzerbild', 'entity_picture') }}"`,
      ].join("\n"),
    )
    .join("\n\n");

  return [
    "# FYTA plant sensor bridges — generated by scripts/generate-plant-sensors.mjs",
    "# Place in your HA config packages directory and reload template entities.",
    "template:",
    "  - sensor:",
    sensors,
    "",
  ].join("\n");
}

const ws = new WebSocket("ws://homeassistant.local:8123/api/websocket");
ws.onerror = (err) => {
  console.error("✘ WebSocket error:", err.message);
  process.exit(1);
};
function send(obj) {
  ws.send(JSON.stringify(obj));
}
let msgId = 1;

ws.onmessage = (event) => {
  const msg = JSON.parse(event.data);
  if (msg.type === "auth_required") {
    send({ type: "auth", access_token: TOKEN });
  } else if (msg.type === "auth_ok") {
    send({ id: msgId++, type: "get_states" });
  } else if (msg.type === "result") {
    if (!msg.success || !Array.isArray(msg.result)) {
      console.error("✘ get_states failed:", JSON.stringify(msg.error));
      ws.close();
      process.exit(1);
    }
    const entities = msg.result;
    const prefixes = entities
      .map((e) => e.entity_id)
      .filter((id) => /^sensor\.[a-z0-9_]+_moisture_state$/.test(id))
      .map((id) => id.replace(/^sensor\./, "").replace(/_moisture_state$/, ""))
      .sort();

    if (prefixes.length === 0) {
      console.error("✘ No sensor.*_moisture_state entities found");
      ws.close();
      process.exit(1);
    }

    const yaml = generateYaml(prefixes);

    mkdirSync(dirname(outputPath), { recursive: true });
    writeFileSync(outputPath, yaml, "utf8");

    console.log(`✔ Found ${prefixes.length} plants: ${prefixes.join(", ")}`);
    console.log(`✔ Written to ${outputPath}`);

    ws.close();
  }
};
ws.onclose = () => process.exit(0);
setTimeout(() => {
  console.error("✘ Timeout");
  process.exit(1);
}, 8000);
